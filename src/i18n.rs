/// Equivalent du MODE EXPERT d'un texte du mode simple (glossaire ETUDE §6.1 : on garde les mots techniques d'origine).
/// Identite pour les textes communs aux deux modes. Memes marqueurs de format que la cle simple (verifie par test).
pub fn expert_variant(k: K) -> K {
    match k {
        K::VMyProtections => K::NavGames,
        K::VProtectSomething => K::NavAdd,
        K::VProtectIt => K::BtnPropYes,
        K::VProgram => K::LocExe,
        K::VVault => K::SetDest,
        K::VSafe => K::StatusUpToDate,
        K::VPending => K::StatusLocalChanged,
        K::VNewerArrived => K::StatusCloudNewer,
        K::VRestoreThis => K::VersionRestore,
        K::VTimeTravel => K::VersionsTitle,
        K::VConflict => K::StatusConflict,
        K::VKnown => K::ProfTitle,
        K::VProtectionOn => K::WatchRunning,
        K::VStopProtecting => K::BtnRemove,
        K::VSyncAllNow => K::SyncNow,
        // lot 11 : page Ajouter (equivalents techniques d'origine)
        K::VAddExistingTitle => K::AddExisting,
        K::VAddExistingHint => K::AddExistingHint,
        K::VAddRejoin => K::BtnJoin,
        K::VAddSimilar => K::SimilarAlert,
        K::VAddOverlapTitle => K::OverlapTitle,
        K::VAddOverlapBody => K::ConfOverlap,
        K::VAddFormProgram => K::AddManual,
        other => other,
    }
}

/// Texte de la cle `k` dans le mode `mode` (simple : la cle ; expert : son equivalent technique), avec le vocabulaire de
/// la plateforme courante.
pub fn tr_mode(l: Lang, mode: Mode, k: K) -> &'static str {
    match mode {
        Mode::Simple => tr(l, k),
        Mode::Expert => tr(l, expert_variant(k)),
    }
}
