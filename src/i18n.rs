//! Internationalisation : une table (cle -> FR, EN) dans ce fichier, plus une traduction par langue
//! supplementaire (`i18n_ru`, `i18n_es`, `i18n_zh`, `match` EXHAUSTIFS : une cle sans traduction ne compile pas).
//! Les traductions RU / ES / ZH sont automatiques et n'ont pas ete relues par des locuteurs natifs.
use serde::{Deserialize, Serialize};
use std::sync::atomic::{AtomicBool, Ordering};

#[derive(Serialize, Deserialize, Clone, Copy, PartialEq, Eq, Debug)]
#[serde(rename_all = "lowercase")]
pub enum Lang {
    Fr,
    En,
    Ru,
    Es,
    Zh,
}

impl Lang {
    /// Toutes les langues, dans l'ordre d'affichage des selecteurs.
    pub const ALL: [Lang; 5] = [Lang::En, Lang::Fr, Lang::Ru, Lang::Es, Lang::Zh];

    /// Nom de la langue dans sa propre langue (convention : volontairement non traduit).
    pub fn native_name(self) -> &'static str {
        match self {
            Lang::En => "English",
            Lang::Fr => "Français",
            Lang::Ru => "Русский",
            Lang::Es => "Español",
            Lang::Zh => "中文",
        }
    }

    /// Code court (journal, diagnostics).
    pub fn code(self) -> &'static str {
        match self {
            Lang::En => "en",
            Lang::Fr => "fr",
            Lang::Ru => "ru",
            Lang::Es => "es",
            Lang::Zh => "zh",
        }
    }
}

/// Une police couvrant le chinois est-elle chargee ? (renseigne par l'interface) Sinon le chinois se replie sur l'anglais :
/// mieux vaut de l'anglais lisible que des carres.
static CJK_FONT_OK: AtomicBool = AtomicBool::new(true);

pub fn set_cjk_font_available(ok: bool) {
    CJK_FONT_OK.store(ok, Ordering::SeqCst);
}

pub fn cjk_font_available() -> bool {
    CJK_FONT_OK.load(Ordering::SeqCst)
}

macro_rules! keys {
    ($($id:ident => ($fr:expr, $en:expr)),* $(,)?) => {
        #[derive(Clone, Copy, Debug, PartialEq, Eq)]
        pub enum K { $($id),* }
        pub const ALL_KEYS: &[K] = &[$(K::$id),*];
        fn tr_fr_en(fr: bool, k: K) -> &'static str {
            match k { $(K::$id => if fr { $fr } else { $en }),* }
        }
    };
}

