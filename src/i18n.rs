/// Cle reellement affichee sur CETTE plateforme (Windows : la cle elle-meme ; Linux : sa variante).
#[inline]
pub fn platform_key(k: K) -> K {
    #[cfg(windows)]
    {
        k
    }
    #[cfg(not(windows))]
    {
        linux_variant(k)
    }
}

/// Texte de la cle `k` dans la langue `l` (le chinois se replie sur l'anglais sans police CJK), avec le vocabulaire de
/// la plateforme courante.
pub fn tr(l: Lang, k: K) -> &'static str {
    tr_raw(l, platform_key(k))
}

/// Langue reellement affichee (le chinois sans police CJK s'affiche en anglais).
fn shown_lang(l: Lang) -> Lang {
    if l == Lang::Zh && !cjk_font_available() { Lang::En } else { l }
}

/// Forme du singulier pour `n` ? Francais : 0 et 1 (« 0 fichier modifie ») ; anglais, espagnol : 1 seulement ; russe et
/// chinois : 1 (les textes russes au pluriel sont tournes « Nom : N », valables pour tout nombre).
pub fn is_singular(l: Lang, n: u64) -> bool {
    match shown_lang(l) {
        Lang::Fr => n <= 1,
        _ => n == 1,
    }
}

/// Cle `one` ou `many` selon `n` (regle de `is_singular`).
pub fn pick_n(l: Lang, n: u64, one: K, many: K) -> K {
    if is_singular(l, n) { one } else { many }
}

/// Elision du francais apres remplacement d'un nom ou d'une date : « de aujourd'hui » -> « d'aujourd'hui », « de hier »
/// -> « d'hier », « de ALLY » -> « d'ALLY » (mot « de » suivi d'une voyelle, ou de « hier »). Autres langues : inchange.
pub fn elide(l: Lang, s: &str) -> String {
    if shown_lang(l) != Lang::Fr {
        return s.to_string();
    }
    const V: &str = "aeiouyàâäéèêëîïôöùûüAEIOUYÀÂÄÉÈÊËÎÏÔÖÙÛÜ";
    let mut out = String::with_capacity(s.len());
    let mut rest = s;
    while let Some(i) = rest.find("de ") {
        let before_ok = rest[..i].chars().next_back().map(|c| !c.is_alphanumeric() && c != '\'' && c != '’').unwrap_or(out.chars().next_back().map(|c| !c.is_alphanumeric()).unwrap_or(true));
        let after = &rest[i + 3..];
        let next = after.chars().next();
        let elide = before_ok && (next.map(|c| V.contains(c)).unwrap_or(false) || after.to_lowercase().starts_with("hier"));
        out.push_str(&rest[..i]);
        out.push_str(if elide { "d'" } else { "de " });
        rest = after;
    }
    out.push_str(rest);
    out
}

/// « Par rapport à maintenant : 1 fichier modifié, 3 ajoutés » : chaque nombre accorde son propre texte.
pub fn diff_now(l: Lang, replaced: u64, added: u64) -> String {
    let c = tr(l, pick_n(l, replaced, K::VDiffChangedOne, K::VDiffChangedMany)).replace("{}", &replaced.to_string());
    let a = tr(l, pick_n(l, added, K::VDiffAddedOne, K::VDiffAddedMany)).replace("{}", &added.to_string());
    tr(l, K::VDiffNow).replace("{0}", &c).replace("{1}", &a)
}

/// Taille lisible dans la langue `l` : unites et separateur decimal de la langue (« 7,1 Mo » en francais, « 7.1 MB » en
/// anglais, « 7,1 MB » en espagnol, « 7,1 МБ » en russe, « 7.1 MB » en chinois). Base 1024 comme `actions::format_bytes`.
pub fn format_bytes(l: Lang, b: u64) -> String {
    let (units, comma): ([&str; 5], bool) = match shown_lang(l) {
        Lang::Fr => (["o", "Ko", "Mo", "Go", "To"], true),
        Lang::En => (["B", "KB", "MB", "GB", "TB"], false),
        Lang::Ru => (["Б", "КБ", "МБ", "ГБ", "ТБ"], true),
        Lang::Es => (["B", "KB", "MB", "GB", "TB"], true),
        Lang::Zh => (["B", "KB", "MB", "GB", "TB"], false),
    };
    let mut v = b as f64;
    let mut i = 0;
    while v >= 1024.0 && i < units.len() - 1 {
        v /= 1024.0;
        i += 1;
    }
    if i == 0 {
        return format!("{} {}", b, units[0]);
    }
    let n = format!("{:.1}", v);
    format!("{} {}", if comma { n.replace('.', ",") } else { n }, units[i])
}

/// Texte tel qu'il s'affiche sous Linux, quelle que soit la plateforme de compilation (tests de vocabulaire).
pub fn tr_linux(l: Lang, k: K) -> &'static str {
    tr_raw(l, linux_variant(k))
}

/// Texte EXACT de la cle `k` (aucune variante de plateforme).
pub fn tr_raw(l: Lang, k: K) -> &'static str {
    match l {
        Lang::Fr => tr_fr_en(true, k),
        Lang::En => tr_fr_en(false, k),
        Lang::Ru => crate::i18n_ru::tr(k),
        Lang::Es => crate::i18n_es::tr(k),
        Lang::Zh if cjk_font_available() => crate::i18n_zh::tr(k),
        Lang::Zh => tr_fr_en(false, k),
    }
}

